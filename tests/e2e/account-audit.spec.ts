import { expect, test } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { hashPassword } from '../../apps/web/server/security.js';
const db = new PrismaClient(); test.afterAll(() => db.$disconnect());
test('complete client signup, profile, admin verification, account change and logout journey', async ({page,browser},info) => {
  const prefix = `audit-${info.project.name}-${Date.now()}`,email = prefix+'@example.test',password = 'Synthetic audit passphrase only!';
  const username = `AUDIT_${Date.now()}`,adminEmail = prefix+'-admin@example.test';
  const adminContext = await browser.newContext({viewport:page.viewportSize()!});
  const adminUser = await db.user.create({data:{name:'Synthetic audit admin',email:adminEmail,username,role:'ADMIN',passwordHash:await hashPassword(password)}});
  const base = 'http://127.0.0.1:3001';
  try {
    await page.goto('/auth/register');
    await expect(page.locator('[name=brokerName]')).toHaveCount(0);
    await page.getByLabel('Display name',{exact:true}).fill('Audit Client');
    await page.getByLabel('Email address').fill(email); await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Create account',exact:true}).click();
    await expect(page).toHaveURL(/\/auth\/login\?registered=1$/);
    await page.getByLabel('Email or admin username').fill(email); await page.getByLabel('Password',{exact:true}).fill('Wrong synthetic password!');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page.locator('[data-form-message]')).toContainText('incorrect');
    await page.getByLabel('Password',{exact:true}).fill(password); await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page).toHaveURL(/\/app\/mapping$/);
    await page.goto('/app/settings'); await expect(page.getByLabel('Display name',{exact:true})).toHaveValue('Audit Client');
    await expect(page.getByLabel('Email',{exact:true})).toHaveValue(email);
    await page.goto('/app/membership'); await expect(page.locator('[data-membership-status]')).toHaveText('FREE');
    await page.getByLabel('MT5 account number',{exact:true}).fill('00123456');
    await page.getByLabel('Qualifying deposit (USD)',{exact:true}).fill('100');
    await page.getByRole('button',{name:'Submit verification request',exact:true}).click();
    await expect(page.locator('[data-membership-status]')).toHaveText('PENDING');
    await page.screenshot({path:`docs/screenshots/${info.project.name}-audit-membership-pending.png`,fullPage:true});
    const admin = await adminContext.newPage(); await admin.goto(base+'/auth/login');
    await admin.getByLabel('Email or admin username').fill(username.toLowerCase());
    await admin.getByLabel('Password',{exact:true}).fill(password); await admin.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(admin).toHaveURL(base+'/admin');
    await admin.goto(base+'/admin/members'); await admin.getByLabel('Search clients').fill(email); await admin.getByRole('button',{name:'Search',exact:true}).click();
    const card = admin.locator('.client-record').filter({hasText:email}); await expect(card).toContainText('00123456');
    await card.getByRole('button',{name:'Approve',exact:true}).click();
    const dialog = admin.getByRole('dialog',{name:'Client membership review'});
    const review = dialog.locator('.membership-review').filter({hasText:email});
    await expect(dialog).toBeVisible(); await expect(review.getByLabel('Verified MT5 account (last four digits)')).toHaveValue('3456');
    await expect(review.getByLabel('Review reason (visible to the member)')).toBeHidden();
    await review.getByLabel('Verified qualifying deposit (USD)').fill('100'); await review.getByRole('checkbox').check();
    await admin.screenshot({path:`docs/screenshots/${info.project.name}-audit-admin-review.png`,fullPage:true});
    await review.getByRole('button',{name:'Approve membership',exact:true}).click(); await expect(dialog).not.toBeVisible(); await expect(card).toContainText('APPROVED');
    await page.goto('/app/mt5'); await expect(page.getByRole('heading',{name:'Coming soon',exact:true})).toBeVisible();
    await expect(page.locator('[data-v2-trade]')).toHaveCount(0);
    await page.goto('/app/academy'); await expect(page.locator('[data-education]')).toBeVisible();
    await page.goto('/app/settings'); await page.getByLabel('Display name',{exact:true}).fill('Updated Audit Client');
    await page.getByRole('button',{name:'Save account details',exact:true}).click();
    await expect(page.locator('[data-profile-status]')).toContainText('Account details saved');
    await page.reload(); await expect(page.getByLabel('Display name',{exact:true})).toHaveValue('Updated Audit Client');
    await page.goto('/app/academy'); await expect(page).toHaveURL(/academy$/);
    await page.goto('/app/settings'); await page.getByLabel('MT5 account number',{exact:true}).fill('00987654');
    await page.getByRole('button',{name:'Save account details',exact:true}).click();
    await expect(page.locator('[data-profile-status]')).toContainText('requires a new verification');
    await page.reload(); await expect(page.getByLabel('MT5 account number',{exact:true})).toHaveValue('00987654');
    await page.goto('/app/academy'); await expect(page).toHaveURL(/membership/);
    await page.goto('/app/community'); await expect(page.getByRole('button',{name:'Send message',exact:true})).toBeEnabled();
    if (await page.getByRole('button',{name:'Open navigation',exact:true}).isVisible()) await page.getByRole('button',{name:'Open navigation',exact:true}).click();
    await page.locator('[data-logout]:visible').first().click(); await expect(page).toHaveURL(/\/auth\/login$/);
    await page.goto('/app/settings'); await expect(page).toHaveURL(/\/auth\/login/);
  } finally {
    await adminContext.close();
    await db.user.deleteMany({where:{email:{in:[email,adminEmail]}}});
    void adminUser;
  }
});
