import { expect, test, type BrowserContext } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { digestToken, newToken } from '../../apps/web/server/security.js';
const db = new PrismaClient();
test.afterAll(async () => { await db.$disconnect(); });
test('admin publishes manual game plans and signals to a free member portal', async ({ page, browser }, testInfo) => {
  const prefix = `editorial-ui-${testInfo.project.name}-${Date.now()}`;
  const date = `2043-04-${19 + ['desktop', 'ipad', 'mobile'].indexOf(testInfo.project.name)}`;
  const adminContext = await browser.newContext({ viewport: page.viewportSize()! });
  const signIn = async (context: BrowserContext, name: string, role: 'MEMBER' | 'ADMIN') => {
    const user = await db.user.create({ data: { name, email: `${prefix}-${name}@example.test`, role, passwordHash: 'synthetic-no-password-login' } });
    const token = newToken(); await db.session.create({ data: { userId: user.id, tokenHash: digestToken(token), expiresAt: new Date(Date.now() + 600000) } });
    await context.addCookies([{ name: '__Host-yengfx_session', value: token, domain: '127.0.0.1', path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }]);
  };
  try {
    await signIn(page.context(), 'reader', 'MEMBER'); await signIn(adminContext, 'admin', 'ADMIN');
    const admin = await adminContext.newPage(); await admin.goto('http://127.0.0.1:3001/admin/mapping');
    await expect(admin.getByRole('button', { name: 'New plan', exact: true })).toBeEnabled();
    await expect(admin.locator('[data-editorial-status]')).not.toContainText('Loading');
    await admin.getByRole('button', { name: 'New plan', exact: true }).click();
    await admin.getByLabel('Plan date', { exact: true }).fill(date);
    await admin.getByLabel('Plan title').fill(`${prefix} game plan`);
    await admin.getByLabel('Market Bias').selectOption('BEARISH');
    const description = `${prefix} — <img src=x onerror=alert(1)> Synthetic description for UI testing only.`;
    await admin.getByLabel("Today's game plan / Description").fill(description);
    await admin.getByRole('button', { name: 'Save draft', exact: true }).click();
    await expect(admin.locator('[data-editorial-status]')).toContainText('Draft saved');
    await page.goto('/app/mapping');
    await page.getByLabel('Plan date', { exact: true }).fill(date);
    await page.getByRole('button', { name: 'Load plan', exact: true }).click();
    await expect(page.locator('[data-editorial-status]')).toContainText('No published');
    await admin.getByRole('button', { name: 'Publish', exact: true }).click();
    await expect(admin.locator('[data-editorial-status]')).toContainText('Published for all');
    await page.getByRole('button', { name: 'Load plan', exact: true }).click();
    const plan = page.locator('[data-editorial-items] article').filter({ hasText: `${prefix} game plan` });
    await expect(plan).toContainText('BEARISH'); await expect(plan).toContainText(description);
    await expect(plan.locator('img')).toHaveCount(0);
    await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-published-mapping.png`, fullPage: true });
    await admin.screenshot({ path: `docs/screenshots/${testInfo.project.name}-mapping-editor.png`, fullPage: true });
    await admin.getByRole('button', { name: 'Archive', exact: true }).click();
    await expect(admin.locator('[data-editorial-status]')).toContainText('Archived');
    await page.getByRole('button', { name: 'Load plan', exact: true }).click();
    await expect(page.locator('[data-editorial-items]')).not.toContainText(description);
    await admin.goto('http://127.0.0.1:3001/admin/signals');
    await expect(admin.locator('[data-editorial-status]')).not.toContainText('Loading');
    await admin.getByLabel('Signal title').fill(`${prefix} manual signal`);
    await admin.getByLabel('Direction', { exact: true }).selectOption('BUY');
    await admin.getByLabel('Trading style').selectOption('INTERDAY');
    for (const [label, value] of [['Zone from (lower price)', '100'], ['Zone to (upper price)', '108'], ['SL', '98'], ['TP1', '112'], ['TP2', '116'], ['TP3', '120']]) await admin.getByLabel(label, { exact: true }).fill(value);
    await admin.getByLabel('Signal notes (optional)').fill('Synthetic prices for UI testing only. Not a real signal.');
    await admin.getByRole('button', { name: 'Publish', exact: true }).click();
    await expect(admin.locator('[data-editorial-status]')).toContainText('Published for all');
    await page.goto('/app/signals');
    const signal = page.locator('[data-editorial-items] article').filter({ hasText: `${prefix} manual signal` });
    await expect(signal).toBeVisible(); await expect(signal).toContainText('INTERDAY');
    await expect(signal.locator('dt')).toHaveText(['ZONE', 'SL', 'TP1', 'TP2', 'TP3']);
    await expect(signal.locator('dd')).toHaveText(['100 – 108', '98', '112', '116', '120']);
    await page.getByRole('button', { name: 'Scalping', exact: true }).click();
    await expect(signal).toHaveCount(0);
    await page.getByRole('button', { name: 'Interday', exact: true }).click();
    await expect(signal).toBeVisible();
    await page.screenshot({ path: `docs/screenshots/${testInfo.project.name}-manual-signals.png`, fullPage: true });
    await admin.screenshot({ path: `docs/screenshots/${testInfo.project.name}-signals-editor.png`, fullPage: true });
    await admin.getByRole('button', { name: 'Archive', exact: true }).click();
    await expect(admin.locator('[data-editorial-status]')).toContainText('Archived');
    await page.getByRole('button', { name: 'Refresh signals', exact: true }).click();
    await expect(signal).toHaveCount(0);
  } finally {
    await adminContext.close().catch(() => {});
    await db.dailyPlan.deleteMany({ where: { title: { startsWith: prefix } } });
    await db.manualSignal.deleteMany({ where: { title: { startsWith: prefix } } });
    await db.user.deleteMany({ where: { email: { startsWith: prefix } } });
  }
});
