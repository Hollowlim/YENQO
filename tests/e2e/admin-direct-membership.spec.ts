import { test, expect, type BrowserContext } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { newToken, digestToken } from '../../apps/web/server/security.js';
const db = new PrismaClient(); test.afterAll(async () => { await db.$disconnect(); });
test('homepage accordion expands with focus and tap and respects reduced motion', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const gallery = page.locator('[data-accordion-gallery]');
  const triggers = gallery.locator('.gallery-trigger');
  await gallery.scrollIntoViewIfNeeded();
  await expect(gallery.locator('.gallery-art img')).toHaveCount(3);
  await expect.poll(() => gallery.locator('.gallery-art img').evaluateAll(nodes => nodes.every(node => node instanceof HTMLImageElement && node.complete && node.naturalWidth > 0))).toBe(true);
  await expect(triggers).toHaveCount(3);
  await expect(triggers.nth(1)).toHaveAttribute('aria-expanded', 'true');
  await triggers.first().click();
  await expect(triggers.first()).toHaveAttribute('aria-expanded', 'true');
  await expect(gallery.getByRole('link', { name: 'Explore Tools', exact: true })).toBeVisible();
  await triggers.nth(2).focus();
  await expect(triggers.nth(2)).toHaveAttribute('aria-expanded', 'true');
  await expect(gallery.getByRole('link', { name: 'Explore Educations', exact: true })).toBeVisible();
  await expect(gallery.locator('.gallery-caption').first()).toHaveJSProperty('inert', true);
  await triggers.nth(1).click();
  await expect(triggers.nth(1)).toHaveAttribute('aria-expanded', 'true');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(gallery.locator('.gallery-panel').first()).toHaveCSS('transition-duration', '0s');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await gallery.screenshot({ path: `docs/screenshots/${info.project.name}-accordion-gallery.png` });
  expect(errors).toEqual([]);
});
test('registration proceeds to login and passwords can be shown or hidden', async ({ page }) => {
  await page.goto('/auth/register');
  await page.getByLabel('Display name').fill('Preview Client');
  await page.getByLabel('Email address').fill('preview@example.test');
  const password = page.getByLabel('Password', { exact: true });
  await password.fill('Synthetic test passphrase only!');
  await expect(password).toHaveAttribute('type', 'password');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(password).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'Hide password', exact: true }).click();
  await expect(password).toHaveAttribute('type', 'password');
  await page.route('**/api/auth/register', route => route.fulfill({ status: 201, contentType: 'application/json', body: JSON.stringify({ message: 'Account created.' }) }));
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page).toHaveURL(/\/auth\/login\?registered=1$/);
  await expect(page.getByRole('status')).toContainText('Account created. Sign in to continue.');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'Hide password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password');
});
test('admin approves a free registration then manually revokes for MC and changed IB', async ({ page, browser }, info) => {
  const prefix = `direct-ib-ui-${info.project.name}-${Date.now()}`, context = await browser.newContext({ viewport: page.viewportSize()! });
  const create = async (target: BrowserContext, role: 'ADMIN' | 'MEMBER') => {
    const user = await db.user.create({ data: { name: prefix + role, role, email: `${prefix}-${role}@example.test`, passwordHash: 'synthetic-no-login', ...(role === 'MEMBER' ? { brokerName: 'JUSTMARKET', mt5Account: '00123456', membership: { create: { status: 'FREE' } } } : {}) } });
    const token = newToken(); await db.session.create({ data: { userId: user.id, tokenHash: digestToken(token), expiresAt: new Date(Date.now()+600000) } });
    await target.addCookies([{ name: '__Host-yengfx_session', value: token, domain: '127.0.0.1', path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }]);
    return user;
  };
  try {
    await create(page.context(), 'ADMIN'); const member = await create(context, 'MEMBER');
    await page.goto('/admin/members'); const review = page.locator('.membership-review').filter({ hasText: member.email });
    const dialog = page.getByRole('dialog', { name: 'Client membership review' });
    await expect(dialog).not.toBeVisible();
    const clientCard = page.locator('.client-record').filter({ hasText: member.email });
    await expect(clientCard.getByRole('button', { name: 'Revoke', exact: true })).toBeDisabled();
    await clientCard.getByRole('button', { name: 'Approve', exact: true }).click();
    await expect(dialog).toBeVisible();
    await expect(review.getByRole('heading')).toContainText('FREE');
    await expect(review.getByLabel('Review action')).toBeFocused();
    const reader = await context.newPage(); await reader.goto('http://127.0.0.1:3001/app/academy'); await expect(reader).toHaveURL(/membership/);
    await expect(reader.getByLabel('MT5 account number', { exact: true })).toBeVisible();
    await expect(reader.locator('[name="depositAmount"]')).toBeVisible();
    await expect(reader.locator('[name="depositReference"]')).toHaveCount(0);
    await expect(reader.locator('.pixel-plan')).toHaveCount(2);
    await expect(reader.locator('.pixel-plan-gold')).toContainText('Admin approval required');
    await reader.screenshot({ path: `docs/screenshots/${info.project.name}-pixel-membership.png`, fullPage: true });
    const approve = async () => {
      await review.getByLabel('Verified qualifying deposit (USD)').fill('100'); await review.getByRole('checkbox').check();
      await expect(review.getByLabel('Review reason (visible to the member)')).toBeHidden();
      await review.getByRole('button', { name: 'Approve membership' }).click(); await expect(dialog).not.toBeVisible();
      await expect(clientCard).toContainText('APPROVED');
    };
    await approve(); await reader.goto('http://127.0.0.1:3001/app/academy'); await expect(reader).toHaveURL(/academy$/);
    await expect(clientCard.getByRole('button', { name: 'Approve', exact: true })).toBeDisabled();
    await clientCard.getByRole('button', { name: 'Revoke', exact: true }).click();
    await expect(review.getByLabel('Review action')).toHaveValue('revoke');
    await review.getByLabel('Revoke reason', { exact: true }).selectOption('MC'); await review.getByRole('button', { name: 'Revoke access' }).click();
    await expect(dialog).not.toBeVisible(); await expect(clientCard).toContainText('REVOKED');
    await reader.goto('http://127.0.0.1:3001/app/academy'); await expect(reader).toHaveURL(/membership/);
    await clientCard.getByRole('heading').click(); await expect(dialog).toBeVisible();
    await approve(); await clientCard.getByRole('button', { name: 'Revoke', exact: true }).click(); await review.getByLabel('Revoke reason', { exact: true }).selectOption('IB_CHANGED'); await review.getByRole('button', { name: 'Revoke access' }).click();
    await expect(dialog).not.toBeVisible(); await expect(clientCard).toContainText('REVOKED');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: `docs/screenshots/${info.project.name}-direct-membership-review.png`, fullPage: true });
  } finally { await context.close().catch(() => {}); await db.user.deleteMany({ where: { email: { startsWith: prefix } } }); }
});
